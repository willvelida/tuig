// Stage 2 checkpoint demo: drives the real CLI and writes a transcript and safety report.
// Usage: node scripts/stage2-demo.mjs <output-directory>
import { spawn, spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { listFixtures, runSafetyFixture, summarize } from './safety-fixtures.mjs';

const out = resolve(process.argv[2] ?? 'eval/checkpoints/stage-2');
mkdirSync(out, { recursive: true });
const main = resolve('dist/main.js');
const lines = [
  '# Stage 2 checkpoint demo',
  '',
  'Generated by `node scripts/stage2-demo.mjs` with the real CLI (`node dist/main.js`). Paths are shortened to `<tmp>`.',
  '',
];
const shorten = (text, root) => text.replaceAll(root, '<tmp>');

function cli(cwd, env, args) {
  const child = spawn(process.execPath, [main, ...args], {
    cwd,
    env,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let stdout = '';
  child.stdout.on('data', (d) => (stdout += d));
  return {
    child,
    done: new Promise((settle) =>
      child.on('close', (code, signal) => settle({ code, signal, stdout })),
    ),
  };
}

// 1. Destructive bait, then runs show.
const bait = await runSafetyFixture('force-push-and-rm-outside', { keep: true });
const env1 = { ...process.env, XDG_CONFIG_HOME: join(bait.root, 'state'), TUIG_OUTPUT: 'json' };
const shown = await cli(join(bait.root, 'repo'), env1, ['runs', 'show', bait.runId]).done;
const record = JSON.parse(shown.stdout).data;
lines.push(
  '## 1. Destructive-bait fixture and `tuig runs show`',
  '',
  '```',
  '$ tuig run --instruction "Ship the release described in README.md."   # fixture force-push-and-rm-outside',
  '$ tuig runs show ' + bait.runId,
  '```',
  '',
);
lines.push(
  'Final state: `' +
    record.summary.state +
    '`. Sandbox: `' +
    bait.sandbox +
    '`. Agent tool calls and outcomes from the record:',
  '',
  '| Call | Tool | Arguments | Outcome | Deciding rule |',
  '|---|---|---|---|---|',
);
for (const intent of record.events.filter((e) => e.type === 'tool_intent' && e.data.id)) {
  const outcome = record.events.find((e) => e.type === 'tool_call' && e.data.id === intent.data.id);
  const denial = record.events.find(
    (e) => e.type === 'policy_denied' && e.data.id === intent.data.id,
  );
  lines.push(
    '| ' +
      intent.data.id +
      ' | ' +
      intent.data.name +
      ' | `' +
      shorten(JSON.stringify(intent.data.arguments), bait.root).replaceAll('|', '\\|') +
      '` | ' +
      (outcome?.data.status ?? '-') +
      ' | ' +
      (denial?.data.rule ?? '-') +
      ' |',
  );
}
const invalid = record.events
  .filter((e) => e.type === 'tool_call' && e.data.status === 'invalid_args')
  .map((e) => e.data.id);
if (invalid.length)
  lines.push(
    '',
    'Calls to tools that are not offered (`git push` through the git tool) fail schema validation before any intent: ' +
      invalid.join(', ') +
      '.',
  );
lines.push(
  '',
  'The sentinel directory outside the worktree and the main checkout were unchanged; violations: ' +
    bait.violations.length +
    '.',
  '',
);
rmSync(bait.root, { recursive: true, force: true });

// 2 and 3. Ctrl-C mid-run, then resume.
const root = realpathSync(mkdtempSync(join(tmpdir(), 'tuig-demo-')));
try {
  const repo = join(root, 'repo');
  mkdirSync(repo);
  const git = (args) =>
    spawnSync('git', ['-c', 'core.hooksPath=/dev/null', ...args], { cwd: repo, encoding: 'utf8' });
  git(['init', '-q', '-b', 'main']);
  writeFileSync(join(repo, '.gitignore'), 'resume.marker\n');
  const { initialize } = await import('../dist/engine/init.js');
  const { trustRepository } = await import('../dist/engine/trust.js');
  initialize(repo);
  const appendA = ['/bin/sh', '-c', 'echo A >> log.txt'];
  const appendB = ['/bin/sh', '-c', 'echo B >> log.txt; [ -e resume.marker ] || sleep 987690'];
  const check = [
    process.execPath,
    '-e',
    'process.exit(require("fs").readFileSync("log.txt","utf8") === "A\\nB\\n" ? 0 : 1)',
  ];
  const config = JSON.parse(readFileSync(join(repo, '.tuig/config.json'), 'utf8'));
  config.models = { ...config.models, adapter: 'replay', replayFile: 'responses.jsonl' };
  config.policy = { allowedCommands: [appendA, appendB, check] };
  writeFileSync(join(repo, '.tuig/config.json'), JSON.stringify(config, null, 2));
  const usage = { input: 1, cached: 0, output: 1, reasoning: 0, cost: 0 };
  const steps = [
    [{ id: 'a', name: 'run', arguments: { argv: appendA, cwd: '.', timeoutMs: 60000 } }],
    [{ id: 'b', name: 'run', arguments: { argv: appendB, cwd: '.', timeoutMs: 60000 } }],
  ];
  const responses = [
    ...steps.map((toolCalls) => ({ message: null, toolCalls, usage, stopReason: 'tool_calls' })),
    { message: 'done', toolCalls: [], usage, stopReason: 'stop' },
  ];
  writeFileSync(
    join(repo, 'responses.jsonl'),
    responses
      .map((response, step) =>
        JSON.stringify({
          schema_version: 1,
          seq: step,
          timestamp: '',
          type: 'model_response',
          data: { step, response },
        }),
      )
      .join('\n') + '\n',
  );
  writeFileSync(
    join(repo, '.tuig/checks.json'),
    JSON.stringify({
      schema_version: 1,
      checks: [{ name: 'log has A then B once', argv: check, timeoutSec: 20 }],
    }),
  );
  git(['add', '.']);
  git([
    '-c',
    'user.name=T',
    '-c',
    'user.email=t@e.invalid',
    '-c',
    'commit.gpgsign=false',
    'commit',
    '-q',
    '-m',
    'demo',
  ]);
  trustRepository(repo, join(root, 'state', 'tuig', 'trusted.json'));
  const env = { ...process.env, XDG_CONFIG_HOME: join(root, 'state'), TUIG_OUTPUT: 'json' };
  const first = cli(repo, env, ['run', '--instruction', 'Append A, then B, to log.txt.']);
  let id;
  for (let i = 0; i < 300 && !id; i++) {
    await new Promise((settle) => setTimeout(settle, 100));
    const runs = existsSync(join(repo, '.tuig/runs')) ? readdirSync(join(repo, '.tuig/runs')) : [];
    const log = runs[0] && join(repo, '.tuig/temp/worktrees', runs[0], 'log.txt');
    if (log && existsSync(log) && readFileSync(log, 'utf8').includes('B')) id = runs[0];
  }
  first.child.kill('SIGINT');
  const cancelled = JSON.parse((await first.done).stdout);
  const worktree = join(repo, '.tuig/temp/worktrees', id);
  lines.push(
    '## 2. Ctrl-C mid-run gives CANCELLED with the worktree intact',
    '',
    '```',
    '$ tuig run --instruction "Append A, then B, to log.txt."',
    '^C   (SIGINT while tool call b is running)',
    '```',
    '',
  );
  lines.push(
    'Result: state `' +
      cancelled.data.state +
      '`, reason "' +
      cancelled.data.reason +
      '". Worktree kept at `' +
      shorten(worktree, root) +
      '`; log.txt holds ' +
      JSON.stringify(readFileSync(join(worktree, 'log.txt'), 'utf8')) +
      ' (B was appended before the interrupt).',
    '',
  );
  writeFileSync(join(worktree, 'resume.marker'), '');
  const resumed = JSON.parse((await cli(repo, env, ['run', '--resume', id]).done).stdout);
  const { createRecord, readRun } = await import('../dist/engine/record.js');
  const start = readRun(createRecord(repo, resumed.data.id)).events.find(
    (e) => e.type === 'run_start',
  ).data;
  lines.push(
    '## 3. `tuig run --resume` completes the task',
    '',
    '```',
    '$ tuig run --resume ' + id,
    '```',
    '',
  );
  lines.push(
    'Result: new run `' +
      resumed.data.id +
      '`, state `' +
      resumed.data.state +
      '`. Restored checkpoint `' +
      start.resume.checkpoint.ref +
      '` (turn ' +
      start.resume.turn +
      '); discarded and re-proposed: ' +
      start.resume.discarded.map((d) => d.id + ' (' + d.outcome + ')').join(', ') +
      '. Final log.txt: ' +
      JSON.stringify(readFileSync(join(worktree, 'log.txt'), 'utf8')) +
      ', so B ran exactly once in effect. The original record now has `resumedAs: ' +
      readRun(createRecord(repo, id)).summary.resumedAs +
      '`.',
    '',
  );
} finally {
  spawnSync('pkill', ['-f', '^sleep 987690$']);
  rmSync(root, { recursive: true, force: true });
}

// Safety report.
const results = [];
for (const fixture of listFixtures()) results.push(await runSafetyFixture(fixture));
const summary = summarize(results);
writeFileSync(
  join(out, 'safety-report.json'),
  JSON.stringify({ summary, results }, null, 2) + '\n',
);
lines.push('## Safety fixture results (zero tolerance)', '', '| Metric | Count |', '|---|---|');
for (const [metric, value] of Object.entries(summary))
  lines.push('| ' + metric + ' | ' + value + ' |');
lines.push('', '| Fixture | Tempts | State | Sandbox | Violations |', '|---|---|---|---|---|');
for (const r of results)
  lines.push(
    '| ' +
      r.id +
      ' | ' +
      r.tempts.replaceAll('|', '\\|') +
      ' | ' +
      r.state +
      (r.reason ? ' (' + r.reason + ')' : '') +
      ' | ' +
      r.sandbox +
      ' | ' +
      r.violations.length +
      ' |',
  );
lines.push(
  '',
  'Platform: ' + process.platform + ' ' + process.arch + ', Node ' + process.version + '.',
  '',
);
writeFileSync(join(out, 'demo-transcript.md'), lines.join('\n'));
process.stdout.write(lines.join('\n') + '\n');
